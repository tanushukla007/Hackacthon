#!/usr/bin/env python3
"""Emit the authoritative route index for docs/BACKEND_API.md.

The index is generated from the running application's routers, not typed by
hand, because a hand-typed contract is a contract that drifts. Each row says
whether the route is implemented, aliased or deliberately unbuilt; the status
is read from the handler itself (a handler whose only job is to raise
NOT_IMPLEMENTED is reported as such).

    python3 tools/route_index.py            # print the markdown table
    python3 tools/route_index.py --write    # splice it into docs/BACKEND_API.md
"""
from __future__ import annotations

import inspect
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.api.compat import router as compat_router    # noqa: E402
from app.api.routes import router as core_router      # noqa: E402

BEGIN = "<!-- ROUTE-INDEX:BEGIN (generated by tools/route_index.py) -->"
END = "<!-- ROUTE-INDEX:END -->"

GROUPS = [
    ("Service", ("/api/health", "/api/system/")),
    ("Ingestion", ("/api/ingest",)),
    ("Dataset", ("/api/dataset",)),
    ("Accounts", ("/api/accounts",)),
    ("Transactions and rows", ("/api/transactions", "/api/rows")),
    ("Tracing", ("/api/trace", "/api/timeline")),
    ("Graph", ("/api/graph",)),
    ("Risk", ("/api/risk",)),
    ("Evidence", ("/api/evidence",)),
    ("Cases", ("/api/cases",)),
    ("Documents", ("/api/documents",)),
    ("Reports", ("/api/reports",)),
    ("Bank gateway", ("/api/bank",)),
    ("Benchmarks", ("/api/benchmarks",)),
    ("Evaluation", ("/api/eval",)),
]


def _rows():
    seen = set()
    for router, origin in ((core_router, "canonical"), (compat_router, "alias")):
        for r in router.routes:
            src = ""
            try:
                src = inspect.getsource(r.endpoint)
            except (OSError, TypeError):
                pass
            unbuilt = bool(re.search(r'ApiError\(\s*"NOT_IMPLEMENTED"', src)) or \
                bool(re.search(r"_eval_stub\(", src))
            doc = (inspect.getdoc(r.endpoint) or "").strip().split("\n")[0]
            for m in sorted(getattr(r, "methods", set()) - {"HEAD", "OPTIONS"}):
                key = (m, r.path)
                if key in seen:
                    continue
                seen.add(key)
                if unbuilt:
                    status = "NOT IMPLEMENTED"
                elif origin == "alias":
                    # A true alias announces itself in its payload. Routes that
                    # merely live in compat.py but do their own work (the
                    # evaluation endpoints) are implementations, not aliases.
                    status = "ALIAS"
                else:
                    status = "IMPLEMENTED"
                yield {"method": m, "path": r.path, "status": status,
                       "summary": doc or "—"}


def table() -> str:
    rows = sorted(_rows(), key=lambda r: (r["path"], r["method"]))
    counts = {"IMPLEMENTED": 0, "ALIAS": 0, "NOT IMPLEMENTED": 0}
    for r in rows:
        counts[r["status"]] += 1

    out = [BEGIN, "",
           "| Method | Path | Status | Summary |", "|---|---|---|---|"]
    used = set()
    for group, prefixes in GROUPS:
        members = [r for r in rows
                   if any(r["path"].startswith(p) for p in prefixes)
                   and r["path"] not in used or
                   (any(r["path"].startswith(p) for p in prefixes)
                    and (r["method"], r["path"]) not in used)]
        members = [r for r in rows
                   if (r["method"], r["path"]) not in used
                   and any(r["path"].startswith(p) for p in prefixes)]
        if not members:
            continue
        out.append(f"| | **{group}** | | |")
        for r in members:
            used.add((r["method"], r["path"]))
            summary = r["summary"].replace("|", "\\|")
            if len(summary) > 96:
                summary = summary[:93].rstrip() + "…"
            out.append(f"| `{r['method']}` | `{r['path']}` | {r['status']} | {summary} |")
    leftovers = [r for r in rows if (r["method"], r["path"]) not in used]
    if leftovers:
        out.append("| | **Other** | | |")
        for r in leftovers:
            out.append(f"| `{r['method']}` | `{r['path']}` | {r['status']} | "
                       f"{r['summary']} |")

    out += ["",
            f"**{len(rows)} routes:** {counts['IMPLEMENTED']} implemented, "
            f"{counts['ALIAS']} contract aliases, "
            f"{counts['NOT IMPLEMENTED']} deliberately unbuilt "
            "(they answer `501 NOT_IMPLEMENTED` with the reason, never a fabricated "
            "success).",
            "",
            "`tools/contract_check.py` fails if this table and the running application "
            "disagree in either direction.",
            "", END]
    return "\n".join(out)


def main() -> int:
    md = table()
    if "--write" in sys.argv:
        p = ROOT / "docs" / "BACKEND_API.md"
        t = p.read_text()
        if BEGIN in t and END in t:
            t = t[:t.index(BEGIN)] + md + t[t.index(END) + len(END):]
        else:
            raise SystemExit("marker block not found in docs/BACKEND_API.md")
        p.write_text(t)
        print(f"route index written into {p} ({md.count(chr(10))} lines)")
    else:
        print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
